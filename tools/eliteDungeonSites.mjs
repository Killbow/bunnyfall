// BUNNYFALL (2026-11-18, daily elite dungeons): THE POOL THE SERVICE PICKS FROM. Walks MAPS.BSA from the player's own
// ARENA2 and writes server-account/src/eliteDungeonSites.js: every dungeon an elite dungeon may be (net/eliteDungeonLaw.js
// edSiteOk - a labyrinth, a keep or a ruin of at least ED_SITE_MIN_BLOCKS blocks, never in Cromwark's region, never a
// main-story dungeon, never a cemetery), one line each: region, location, map pixel x and y, name. The pool lives on the
// service alone (it picks and keeps the rows); the client hears each pick whole.
//
// Usage: ARENA2_PATH=/path/to/arena2 node tools/eliteDungeonSites.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MapsFile, longitudeLatitudeToMapPixel } from '../src/formats/mapsFile.js';
import { isMainStoryDungeon } from '../src/world/dungeonTextures.js';
import { WILD_REGION } from '../src/world/wildZone.js';
import { edSiteOk } from '../src/net/eliteDungeonLaw.js';

const A = process.env.ARENA2_PATH;
if (!A) { console.error('Set ARENA2_PATH to the ARENA2 folder.'); process.exit(1); }
const m = new MapsFile();
m.load(readFileSync(join(A, 'MAPS.BSA')), readFileSync(join(A, 'CLIMATE.PAK')), readFileSync(join(A, 'POLITIC.PAK')));
const rows = [];
for (let r = 0; r < m.regionCount; r++) {
  const reg = m.getRegion(r);
  if (!reg) continue;
  for (let l = 0; l < Math.min(m.baseLocationCount(r), reg.locationCount); l++) {
    const loc = m.getLocation(r, l);
    const t = loc?.mapTableData;
    if (!loc?.hasDungeon || !t) continue;
    if (!edSiteOk({ regionIndex: r, wildRegion: WILD_REGION, locationType: t.locationType, dungeonType: t.dungeonType, blocks: loc.dungeon?.blocks?.length ?? 0, mainStory: isMainStoryDungeon(t.mapId) })) continue;
    const p = longitudeLatitudeToMapPixel(t.longitude, t.latitude);
    const px = Array.isArray(p) ? p[0] : p.x, py = Array.isArray(p) ? p[1] : p.y;
    rows.push([r, l, px, py, String(loc.name).replace(/[|\n]/g, ' ')].join('|'));
  }
}
const out = fileURLToPath(new URL('../server-account/src/eliteDungeonSites.js', import.meta.url));
writeFileSync(out, `// @ts-check
// BUNNYFALL (2026-11-18, daily elite dungeons): GENERATED by tools/eliteDungeonSites.mjs from MAPS.BSA - do not edit by
// hand. Every dungeon an elite dungeon may be (net/eliteDungeonLaw.js edSiteOk), a line each: region|location|px|py|name.
export const ED_SITES_TEXT = ${JSON.stringify(rows.join('\n'))};
`);
console.log(`${rows.length} sites -> ${out}`);
