// BUNNYFALL: holds src/scenes/world.js and the three per-frame loops under the ceilings in tools/worldBudget.json.
// Source counts come from the acorn AST; frame sizes come from V8 bytecode compiled with --no-lazy, and V8 stops
// optimizing a function above 61,440 B. Exit 0 within budget, 1 over budget, 2 when a measurement fails.
// Run: node tools/worldBudgetCheck.mjs
import { spawn } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createInterface } from 'node:readline';
import { parse } from 'acorn';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const budget = JSON.parse(readFileSync(new URL('worldBudget.json', import.meta.url), 'utf8'));
const read = (rel) => readFileSync(ROOT + rel, 'utf8');
const ast = (src) => parse(src, { ecmaVersion: 'latest', sourceType: 'module' });

function fail(msg) { console.error(`worldBudgetCheck: ${msg}`); process.exit(2); }

function sourceCounts(rel, host) {
  const src = read(rel);
  const tree = ast(src);
  const nonEmptyLines = src.split('\n').filter((l) => /\S/.test(l)).length;
  const staticImports = tree.body.filter((n) => n.type === 'ImportDeclaration').length;
  const decl = tree.body.map((n) => (n.type === 'ExportNamedDeclaration' ? n.declaration : n))
    .find((n) => n?.type === 'FunctionDeclaration' && n.id?.name === host);
  if (!decl) fail(`${rel} has no top-level function ${host}`);
  let hostBindings = 0;
  for (const s of decl.body.body) {
    if (s.type === 'VariableDeclaration') hostBindings += s.declarations.length;
    else if (s.type === 'FunctionDeclaration') hostBindings += 1;
  }
  return { nonEmptyLines, staticImports, hostBindings };
}

function frameRange(rel, name) {
  const found = [];
  const walk = (node) => {
    if (!node || typeof node.type !== 'string') return;
    if (node.type === 'FunctionDeclaration' && node.id?.name === name) found.push(node);
    for (const key in node) {
      const v = node[key];
      if (Array.isArray(v)) v.forEach(walk);
      else if (v && typeof v === 'object' && typeof v.type === 'string') walk(v);
    }
  };
  walk(ast(read(rel)));
  if (found.length !== 1) fail(`${rel} has ${found.length} function declarations named ${name}, expected 1`);
  return [found[0].start, found[0].end];
}

const COMPILE = "new (require('node:vm').SourceTextModule)(require('node:fs').readFileSync(process.argv[1], 'utf8'))";

// Compiles the file as a module without linking it, so none of its imports load.
function bytecodeSizes(rel, name) {
  return new Promise((resolve) => {
    const args = ['--experimental-vm-modules', '--no-warnings', '--no-lazy', '--print-bytecode',
      `--print-bytecode-filter=${name}`, '-e', COMPILE, ROOT + rel];
    const child = spawn(process.execPath, args, { stdio: ['ignore', 'pipe', 'pipe'] });
    const blocks = [];
    let cur = null, err = '';
    child.stderr.on('data', (d) => { err += d; });
    createInterface({ input: child.stdout }).on('line', (line) => {
      if (line.startsWith('[generated bytecode for function: ')) { cur = { size: -1, pos: -1 }; blocks.push(cur); return; }
      if (!cur) return;
      if (cur.size < 0 && line.startsWith('Bytecode length: ')) cur.size = Number(line.slice(17));
      else if (cur.pos < 0) { const m = /^\s*(\d+) [SE]> /.exec(line); if (m) cur.pos = Number(m[1]); }
    });
    child.on('close', (code) => {
      if (code !== 0) fail(`bytecode pass on ${rel} exited ${code}\n${err.trim()}`);
      resolve(blocks);
    });
  });
}

async function frameBytecode(rel) {
  const [start, end] = frameRange(rel, 'frame');
  const inside = (await bytecodeSizes(rel, 'frame')).filter((b) => b.pos >= start && b.pos <= end && b.size > 0);
  if (!inside.length) fail(`no bytecode found for frame in ${rel}`);
  return inside.reduce((a, b) => (b.pos < a.pos ? b : a)).size;
}

const t0 = performance.now();
const frameFiles = Object.keys(budget.frameBytecode);
const sizes = Promise.all(frameFiles.map(frameBytecode));
const counts = sourceCounts(budget.file, budget.host);
const rows = [
  [`${budget.file} non-empty lines`, counts.nonEmptyLines, budget.nonEmptyLines, true],
  [`${budget.file} static imports`, counts.staticImports, budget.staticImports, true],
  [`${budget.host} top-level bindings`, counts.hostBindings, budget.hostBindings, true],
  ...(await sizes).map((size, i) => [`${frameFiles[i]} frame bytecode (B)`, size, budget.frameBytecode[frameFiles[i]], false]),
];

const w = Math.max(...rows.map((r) => r[0].length));
let over = 0;
for (const [label, actual, limit, ratchet] of rows) {
  const state = actual > limit ? 'OVER' : ratchet && actual < limit ? 'ok, lower the budget' : 'ok';
  if (actual > limit) over++;
  console.log(`${label.padEnd(w)}  ${String(actual).padStart(7)} / ${String(limit).padStart(7)}  ${state}`);
}
console.log(`${over ? `${over} over budget` : 'ok: within budget'} (${Math.round(performance.now() - t0)} ms, node ${process.version})`);
process.exit(over ? 1 : 0);
