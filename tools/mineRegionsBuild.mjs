// Builds src/net/mine/mineRegions.js: which mine pixels stand in a region with a signature ore, so the relay (which has
// no MAPS.BSA) lays the same mine the page does.
//   ARENA2_PATH=<the game's ARENA2> node tools/mineRegionsBuild.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MapsFile } from '../src/formats/mapsFile.js';
import { mineAt, mineIdOf } from '../src/net/mine/mineSites.js';
import { regionSignature } from '../src/net/nodeLaw.js';
import { MINE_HAUL_ORES } from '../src/net/mine/mineReceipt.js';
import { isMain } from './lib/isMain.mjs';

/** The signature ore of every mine pixel that has one a mine holds: `{ ore: [mineId, ...] }`, ascending. */
export function signatureMines(maps) {
  const out = {};
  for (let py = 0; py < 500; py++) for (let px = 0; px < 1000; px++) {
    if (!mineAt({ px, py, climate: maps.getClimateIndex(px, py), occupied: false })) continue;
    const sig = regionSignature(maps.getRegionIndexAt(px, py));
    if (sig && MINE_HAUL_ORES.includes(sig.ore)) (out[sig.ore] ??= []).push(mineIdOf(px, py));
  }
  return out;
}

if (isMain(import.meta.url)) {
  const dir = process.env.ARENA2_PATH, rd = (f) => new Uint8Array(readFileSync(join(dir, f)));
  const maps = new MapsFile(); maps.load(rd('MAPS.BSA'), rd('CLIMATE.PAK'), rd('POLITIC.PAK'));
  const by = signatureMines(maps);
  const rows = Object.entries(by).map(([ore, ids]) => `  '${ore}': '${ids.map((id, i) => (id - (ids[i - 1] ?? 0)).toString(36)).join(' ')}',`);
  writeFileSync(new URL('../src/net/mine/mineRegions.js', import.meta.url), `// @ts-check
// GENERATED by tools/mineRegionsBuild.mjs (ARENA2_PATH=<the game's ARENA2>): the mine pixels in a region with a signature
// ore (net/nodeLaw.js regionSignature) - the relay has no MAPS.BSA, so the page and the relay both read this table.
// Each ore's mine ids, ascending, as base-36 steps from the one before.
const STEPS = Object.freeze({
${rows.join('\n')}
});

/** @type {Map<number, string>} */
const BY_ID = new Map();
for (const [ore, s] of Object.entries(STEPS)) { let id = 0; for (const d of s.split(' ')) { id += parseInt(d, 36); BY_ID.set(id, ore); } }

/** The signature ore a mine's region gives it, or null (the mine id is mineSites.js mineIdOf). */
export const mineSignatureOre = (/** @type {number} */ mineId) => BY_ID.get(mineId) ?? null;
export const MINE_SIGNATURE_COUNT = BY_ID.size;
`);
  console.log(Object.fromEntries(Object.entries(by).map(([o, a]) => [o, a.length])));
}
