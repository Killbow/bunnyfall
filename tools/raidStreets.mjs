#!/usr/bin/env node
// BUNNYFALL (2026-11-04, the owner: "remove the fallback, if the town has no usable street the raid checks for another
// town"): THE TOWNS A RAID CANNOT MUSTER IN. A raid's waves gather at camps at the town's edge and march its streets
// to its square (systems/raidMuster.js, scenes/raidSitesHost.js way). A town whose walk grid has no streets for that -
// no square, or no way from any of its four edges to it - is struck off the raid table (systems/raidingParties.js
// raidRegions), so the day's roll picks another town instead, the same on every machine.
//
// The walk grid is built here as the streaming host builds it (scenes/pixelBuild.js: CityNavigation over each block's
// automap and ground), both water lanes; a town is struck off only when it has no way in either.
//
//   ARENA2_PATH=/path/to/arena2 node tools/raidStreets.mjs [--dry]
//
// writes src/systems/raidStreetless.js (`--dry`: prints the count alone).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MapsFile } from '../src/formats/mapsFile.js';
import { BlocksFile } from '../src/formats/blocksFile.js';
import { ImgFile } from '../src/formats/imgFile.js';
import { layoutLocation } from '../src/world/locationLayout.js';
import { CityNavigation } from '../src/world/city/cityNavigation.js';
import { gridStreets, streetEdgeCell, RAID_WAY_EXPANSIONS } from '../src/scenes/raidSitesHost.js';
import { findTownPath } from '../src/systems/livingWorld/townPaths.js';
import { raidRegions } from '../src/systems/raidingParties.js';

const A2 = process.env.ARENA2_PATH;
if (!A2) { console.error('set ARENA2_PATH'); process.exit(2); }
const file = (n) => new Uint8Array(readFileSync(join(A2, n)));
const maps = new MapsFile(); maps.load(file('MAPS.BSA'), file('CLIMATE.PAK'), file('POLITIC.PAK'));
const blocks = new BlocksFile(); blocks.load(file('BLOCKS.BSA'));
const picker = new ImgFile(); picker.load(file('TRAV0I01.IMG'), 'TRAV0I01.IMG');
// the table as the game reads it, none struck off yet
const regions = raidRegions(maps, picker.getDFBitmap().data, { all: true }) ?? [];

/** Whether the town's walk grid (one water lane) gives a camp a way to its square from some edge. */
function musters(loc, enhancedWater) {
  const nav = new CityNavigation(loc.width, loc.height);
  for (const b of loc.blocks) {
    const tiles = b.dfBlock.rmbBlock.fldHeader.groundData.groundTiles;
    nav.setBlockData(b.x, b.y, b.dfBlock.rmbBlock.fldHeader.autoMapData, (tx, ty) => tiles[tx][ty].textureRecord, { enhancedWater });
  }
  const s = gridStreets(nav);
  if (!s) return false;
  for (let side = 0; side < 4; side++) {
    const start = streetEdgeCell(nav, s.label, s.id, side);
    if (!start) continue;
    const cells = findTownPath(nav, start, s.square, { maxExpansions: RAID_WAY_EXPANSIONS });
    if (cells && cells.length >= 2) return true;
  }
  return false;
}

const out = [];
let n = 0;
for (const g of regions) {
  for (const t of g.towns) {
    n++;
    let ok = false;
    try {
      const dfLocation = maps.getLocation(g.region, t.index);
      const loc = layoutLocation(dfLocation, maps, blocks, { enhanced: false, windmills: false });
      ok = musters(loc, false) || musters(loc, true);
    } catch (e) { ok = false; }
    if (!ok) out.push(`${g.region}:${t.index}`);
  }
}
console.log(`${n} raid towns, ${out.length} with no street a raid can muster on`);
if (!process.argv.includes('--dry')) {
  const body = `// @ts-check
// GENERATED by tools/raidStreets.mjs - do not edit by hand. BUNNYFALL: the towns a raid cannot muster in (no square, or
// no way from any edge of the town's streets to it - systems/raidMuster.js), as \`<region>:<location index>\`. The raid
// table (systems/raidingParties.js raidRegions) strikes them off, so the day's roll picks another town.
export const RAID_STREETLESS = new Set(${JSON.stringify(out)});
`;
  writeFileSync(new URL('../src/systems/raidStreetless.js', import.meta.url), body);
  console.log('wrote src/systems/raidStreetless.js');
}
