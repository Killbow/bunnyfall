-- AUDIT 32 S1 lays a cloth piece's first-make share on only where no unit BOUGHT WITH SILVER is spent - and since
-- WOVEN-PAYS a loose unit pays (the loom's own cloth of looted or shop-bought Root Tendrils). The piece's `bought_with`
-- cannot say it: a craft that spends a loose and a bought unit together is walled to gold by the loose one. And a
-- pattern is MADE by the craft that laid its first on, not by any craft of it: a craft of the Weavers' cloth before it
-- lays none on, and the first is still owed to the next craft that can pay. So the decision writes what it did.
--
-- `first_paid`: 1 where this craft laid its pattern's first-make share on, 0 where it laid none on (not the first, or
-- its units could not pay). NULL for a row from before it: the service reads such a row as CLOTH-GEMS did - its piece's
-- `bought_with` for the answer, and its pattern made where it was the first and its XP holds the share
-- (server-account/src/professions.js craftAtAnvil, craftAnswer).
ALTER TABLE prof_crafts ADD COLUMN first_paid INTEGER CHECK (first_paid IS NULL OR first_paid IN (0, 1));
