// Every named export here is read as an entrypoint, and workerd refuses to start when one is a string or other
// non-handler value.
export { default } from './worker/entry.js';

export class Room {
  constructor(state, env) {
    this._metrics = new RoomMetrics();
    this._kind = null;
    // Storage counts reach only the METRICS point, so without that binding the proxy is skipped.
    this.state = env?.METRICS ? countedState(state, this._metrics) : state;
    this.env = env ?? {};
    this._verifyKey = undefined;
    this._watch = new Map();
    this._spent = new Map();
    this._owed = new Map();
    this._owedSoon = null;
    this._owedLate = null;
    this._orders = new Map();
    // Bans stay apart from mute orders, so a newer unmute never lifts a ban and an unban never lifts a mute.
    this._bans = new Map();
    this._bansLoad = null;
    this._paces = new Map();
    this._guildOuts = new Map();
    this._guildOutsLoad = null;
    this._roomGuild = null;
    this._guildChat = null;
    this._idx = null;
    this._idxAt = -Infinity;
    this._hellos = null;
    // Secrets are read one id at a time and never listed, since a hub that never drains keeps stale ones.
    this._secrets = new Bounded(HUB_KEEP_MAX);
    this._asecrets = new Bounded(HUB_KEEP_MAX);
    // Each `_no*` set caches accounts known to hold no receipt of its kind; writing such a receipt must clear
    // the set.
    this._noGateRcpt = new Bounded(HUB_KEEP_MAX);
    this._noSdRcpt = new Bounded(HUB_KEEP_MAX);
    this._noKtRcpt = new Bounded(HUB_KEEP_MAX);
    this._noEgRc = new Bounded(HUB_KEEP_MAX);
    this._noSerpentRcpt = new Bounded(HUB_KEEP_MAX);
    this._noRaidRcpt = new Bounded(HUB_KEEP_MAX);
    this._noStarRcpt = new Bounded(HUB_KEEP_MAX);
    this._worldMemo = undefined;
    this._parks = null;
    this._wardenAt = undefined;
    this._attachedAt = new WeakMap();
    this._roomChat = null;
    this._travFan = null;
    this._travClearFan = null;
    this._travOwed = new Map();
    this._partyChat = null;
    this._roomFoes = null;
    this._roomFoesIn = null;
    this._roomOwn = null;
    this._roomOwnIn = null;
    this._roomActs = null;
    this._roomWho = null;
    this._looks = new Map();
    this._roomActBytes = null;
    this._roomQuestBytes = null;
    this._roomWorld = null;
    this._roomSocial = null;
    this._roomRenown = null;
    this._acctIdx = null;
    this._idxSeq = new WeakMap(); this._idxN = 0;
    this._idIdx = null;
    this._giIdx = null;
    this._folds = new WeakMap();
    this._findRoom = null;
    this._everyone = null;
    this._busKey = undefined;
    this._hostMemo = undefined;
    this._seatSaid = undefined;
    this._relayCfg = undefined;
    this._relayCfgAt = -Infinity;
    this._relayCfgP = null;
    this._rfSaid = false;
    this._vsocks = new Map();
    this._vhid = new Set();
    // Only `hd: 1` in a verified token puts a hello here; fields in the frame itself come from the client.
    this._hidHellos = new WeakSet();
    this._vper = new Map();
    this._cper = new Map();
    this._vshut = new Bounded(HUB_KEEP_MAX);
    this._down = new Map();
    this._downT = null;
    this._outbox = new Map();
    this._polls = new Map();
    this._rsBoot = null;
    this._pollWake = null;
    this._toldN = new Map();
    this._countT = null;
    this._up = [];
    this._upGate = new WeakMap();
    this._upT = null;
    this._upBusy = null;
    this._vidIdx = new Map();
    this._vidIdxFull = false;
    this._hubKey = undefined;
    this._hubTotal = null;
    this._hubTotalSaid = null;
    this._hubCountT = null;
    this._hubSyncAt = 0;
    this._hubAlarmed = false;
    this._vseq = 0;
    // Hand-ups and deliveries are numbered under the sender's `_boot`, and a receiver runs each number once, so a
    // resend after a lost answer never runs twice.
    this._boot = crypto.getRandomValues(new Uint32Array(1))[0].toString(36);
    this._upSeq = 0;
    this._upRetry = null;
    this._upInFlight = null;
    this._upHoldUntil = 0;
    this._upBytes = 0;
    this._upSeen = new Map();
    this._downSeq = new Map();
    this._downSeen = null;
    this._downGone = new Set();
    this._pollOn = false;
    this._shardSeen = new Map();
    this._silentAt = 0;
    this._hubKeyKept = null;
    this._swept = false;
    this._subIdx = null;
    this._parties = new Bounded(PARTIES_MAX);
    this._recs = new Bounded(RECS_MAX);
    this._alarmArmed = false;
    this._cool = new Bounded(COOL_MAX);
    this._dead = new Set();
    this._gone = new WeakSet();
    // Meters live on the instance, not the attachment: the runtime refuses a whole attachment write past 2 KiB,
    // and a meter whose write was refused would never advance.
    this._meters = new WeakMap();
    this._fight = undefined;
    this._fightSavedAt = 0;
    this._trails = null;
    this._trailsAt = Date.now();
    this._siege = undefined;
    this._siegeSavedAt = 0;
    this._helloBy = new Map();
    this._receiptKey = undefined;
    this._leaseKey = undefined;
    this._grants = null;
    this._gateFell = undefined;
    this._serpentSiteRec = undefined;
    this._serpentFells = undefined;
    this._event = undefined;
    this._raids = new Bounded(RAID_CACHE_MAX);
    this._raidSavedAt = new Map();
    // A frame that lands while a cleanse is minted is ignored: the input gate holds only for storage, and the
    // mint awaits crypto.
    this._raidCleaning = new Set();
    this._raidSlots = new Map();
    this._raidDays = new Map();
    this._raidTownsKept = undefined;
    this._raidDayRolls = new Map();
    this._stars = new Bounded(4 * STAR_LEDGERS_MAX);
    this._starSavedAt = new Bounded(4 * STAR_LEDGERS_MAX);
    this._starHolding = new Set();
    this._starHeld = undefined;
    this._raidTownsUp = new Map();
    this._raidCleans = undefined;
    this._wdun = null;
    this._wdunSavedAt = 0;
    this._wdunRate = new WeakMap();
    this._wdunKin = new Map();
    this._instanceKin = new Map();
    this._wildLoad = null;
    this._owLoad = null;
    this._roomOw = null;
    this._herald = undefined;
    this._gateSiteRec = undefined;
    this._serpents = undefined;
    this._serpentSavedAt = new Map();
    this._serpentFalling = new Map();
    this._serpentArmedTo = 0;
    this._serpentRestAt = 0;
    try {
      if (state.setWebSocketAutoResponse && typeof WebSocketRequestResponsePair === 'function') state.setWebSocketAutoResponse(new WebSocketRequestResponsePair('{"t":"ping"}', '{"t":"pong"}'));
    } catch {  }
  }
}
